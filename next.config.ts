import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  // Visitor-triggered reads go to each venue from the browser when CORS allows.
  // Pacifica, RiseX (and Drift if the host has moved) fall through `/api/x/{venue}`.
  reactStrictMode: true,
  poweredByHeader: false,
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: [
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "X-Frame-Options", value: "DENY" },
          {
            key: "Permissions-Policy",
            value: "camera=(), microphone=(), geolocation=()",
          },
          {
            // Nothing here is worth a downgrade attack, but the site is static-first
            // and served over TLS everywhere, so there is no cost to refusing plaintext.
            key: "Strict-Transport-Security",
            value: "max-age=63072000; includeSubDomains; preload",
          },
        ],
      },
      {
        source: "/api/:path*",
        headers: [{ key: "X-Robots-Tag", value: "noindex" }],
      },
    ];
  },
};

export default nextConfig;
